def sumar(a,b):
    return a + b
def restar(a,b):
    return a - b
def multiplicar(a,b):
    return a * b
def dividir(a,b):
    return a / b
def potencia(base, exponente):
    return base ** exponente

print(sumar(15,5))
print(restar(15,5))
print(multiplicar(15,5))
print(dividir(15,5))
print(potencia(15,5))

